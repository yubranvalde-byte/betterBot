def replace_value(old_val, new_val):
    return new_val


def merge_dicts(
    old_val: Optional[Dict[str, Any]], new_val: Optional[Dict[str, Any]]
) -> Dict[str, Any]:
    merged = dict(old_val or {})
    if new_val:
        merged.update(new_val)
    return merged


