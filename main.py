def node_helper(state: FactoryState):
    """
    Node 1 (The Helper): Evaluates interview readiness with `gemini-decision-1`
    and conducts a focused Hebrew interview before emitting `<ARTIFACT_BLUEPRINT>`.
    """
    print(">>> Executing Node 1: The Helper")
    user_input = state.get("user_input", "")
    turn_count = 1 + user_input.count("\nUser:")
    concise_attachments = format_context_attachments(state, max_chars=3000)
    full_attachments = format_context_attachments(state, max_chars=12000)
    readiness_input = (
        f"{user_input}\n\n{concise_attachments}" if concise_attachments else user_input
    )
    helper_user_input = (
        f"{user_input}\n\n{full_attachments}" if full_attachments else user_input
    )

    readiness = evaluate_with_decision_model(readiness_input, HELPER_READINESS_QUESTIONS)
    raw_target = (
        readiness.get("target_type") or state.get("target_type") or "SYSTEM_PROMPT"
    ).strip().upper()
    target_type = raw_target if raw_target in VALID_TARGET_TYPES else "SYSTEM_PROMPT"

    suite_hint = (
        " Because TARGET_TYPE is SKILL_SUITE, populate <SUITE_TOPOLOGY> with 2-4 orthogonal atomic skills "
        "(SLUG, SINGLE_RESPONSIBILITY, POSITIVE_TRIGGERS, NEGATIVE_TRIGGERS_VS_SIBLINGS)."
        if target_type == "SKILL_SUITE"
        else " Enforce the Orthogonality Rule: keep tightly coupled workflows in a single SKILL_PACKAGE/HYBRID_BUNDLE and set <SUITE_TOPOLOGY> to None."
    )

    if readiness.get("used_decision_model"):
        ready_prob = float(readiness.get("ready_to_compile", 0.0))
        low_dims = [
            key
            for key in (
                "has_core_objective",
                "has_trigger_or_context",
                "has_output_contract",
            )
            if float(readiness.get(key, 0.0)) < 0.80
        ]
        needs_refs = float(readiness.get("needs_auxiliary_files", 0.0)) >= 0.65
        needs_scripts = is_needs_scripts(readiness, target_type=target_type)
        is_repo_context = is_repo_context_mode(readiness)

        if turn_count >= 3 or (ready_prob >= 0.85 and turn_count >= 2):
            missing_fields_hint = (
                f"Turn count: {turn_count}. Readiness score: {ready_prob:.2f}. "
                f"Recommended TARGET_TYPE: {target_type}. "
                f"Needs auxiliary references/: {needs_refs}. "
                f"Needs helper scripts/: {needs_scripts}. "
                f"Is repo context (AGENTS.md/CLAUDE.md): {is_repo_context}."
                f"{suite_hint} "
                "Compile the full <ARTIFACT_BLUEPRINT> XML immediately in this turn."
            )
        else:
            missing_str = ", ".join(low_dims) if low_dims else "minor workflow nuances"
            missing_fields_hint = (
                f"Turn count: {turn_count}/3. Recommended TARGET_TYPE: {target_type}. "
                f"Dimensions with confidence < 0.80: {missing_str}. "
                f"Needs auxiliary references/: {needs_refs}. "
                f"Needs helper scripts/: {needs_scripts}. "
                f"Is repo context (AGENTS.md/CLAUDE.md): {is_repo_context}."
                f"{suite_hint} "
                "Ask 1-2 targeted Hebrew clarification questions for missing dimensions before compiling."
            )
    else:
        needs_scripts = (
            False
            if target_type == "SYSTEM_PROMPT"
            else bool(state.get("needs_scripts", False))
        )
        is_repo_context = bool(state.get("is_repo_context", False))
        if turn_count >= 3:
            missing_fields_hint = (
                f"Turn count: {turn_count}. Maximum interview turns reached. "
                "Infer remaining defaults and compile the <ARTIFACT_BLUEPRINT> XML immediately."
            )
        else:
            missing_fields_hint = (
                f"Turn count: {turn_count}/3. Conduct focused clarification on core objective, "
                "triggers/scope, and output contract before compiling <ARTIFACT_BLUEPRINT>."
            )

    effort_tier = normalize_effort_tier(state.get("effort_tier"))
    prompt = ChatPromptTemplate.from_messages(
        [
            ("system", HELPER_PROMPT),
            ("human", "{user_input}"),
        ]
    )
    response, telemetry = _invoke_role_with_fallback(
        role="node_1_helper",
        prompt_template=prompt,
        inputs={
            "user_input": helper_user_input,
            "missing_fields_hint": missing_fields_hint,
            "needs_scripts": "True" if needs_scripts else "False",
            "is_repo_context": "True" if is_repo_context else "False",
        },
        model_overrides=state.get("model_overrides"),
        effort_tier=effort_tier,
    )
    content = _normalize_content(response.content)

    if not content.strip():
        print("\n" + "!" * 50)
        print(">>> [CRITICAL] LLM RETURNED EMPTY PAYLOAD")
        print(">>> Inspecting Raw Metadata:")
        print(response.response_metadata)
        print("!" * 50 + "\n")

    update: Dict[str, Any] = {
        "challenger_xml": content,
        "readiness_scores": readiness,
        "target_type": target_type,
        "needs_scripts": needs_scripts,
        "is_repo_context": is_repo_context,
        "model_telemetry": {
            "node_1_helper": telemetry,
            "last_execution": telemetry,
        },
    }
    if has_blueprint_xml(content):
        meta = extract_blueprint_meta(content)
        update["target_type"] = meta["target_type"]
        if meta["slug_name"]:
            update["slug_name"] = meta["slug_name"]
        update["needs_scripts"] = (
            False
            if meta["target_type"] == "SYSTEM_PROMPT"
            else (needs_scripts or has_blueprint_scripts(content))
        )
        update["is_repo_context"] = is_repo_context or is_repo_context_mode(None, content)

    return update


