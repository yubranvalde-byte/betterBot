def route_from_linter(state: FactoryState):
    linter_result = state.get("linter_result") or {}
    if linter_result.get("will_retry"):
        return "node_3_upgrader"
    return "node_4_adjudicator"


def route_from_adjudicator(state: FactoryState):
    logs = state.get("error_log", [])
    if not logs:
        return END

    last_log = logs[-1]
    iteration_count = state.get("iteration_count", 0)

    if "[PASS]" in last_log:
        if (
            get_effort_profile(state.get("effort_tier")).get("auto_red_team")
            and not state.get("red_team_auto_ran")
        ):
            return "node_red_team_auto"
        return END

    if "[ESCALATE]" in last_log:
        return END

    if "[FAIL]" in last_log:
        if iteration_count < MAX_QA_ITERATIONS:
            print(
                f"    -> Routing back to Upgrader (Attempt {iteration_count}/{MAX_QA_ITERATIONS})"
            )
            return "node_3_upgrader"
        else:
            print("    -> Max iterations reached. Forcing ESCALATE.")
            return END
    return END


def route_from_red_team(state: FactoryState):
    report = state.get("red_team_report") or {}
    if (
        report.get("verdict") == "NEEDS_HARDENING"
        and (report.get("patch_directive") or "").strip()
    ):
        return "node_3_upgrader"
    return END


def resolve_next_node(current_node: str, state: FactoryState) -> str:
    """Canonical single source of truth for intra-graph node transitions."""
    if current_node == "node_1_helper":
        return route_from_helper(state)
    if current_node in ("node_2_construct", "node_3_upgrader"):
        return "gate_1_5_linter"
    if current_node == "gate_1_5_linter":
        return route_from_linter(state)
    if current_node == "node_4_adjudicator":
        return route_from_adjudicator(state)
    if current_node == "node_red_team_auto":
        return route_from_red_team(state)
    return END


