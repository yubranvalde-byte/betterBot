def route_from_start(state: FactoryState):
    """
    מנתב את נקודת הכניסה לגרף.
    אם המערכת בהסלמה והמשתמש הזין פקודה ידנית - מדלגים ישירות לעורך (Upgrader).
    אחרת, מתחילים כרגיל מסוכן 1.
    """
    logs = state.get("error_log", [])
    if logs and "[MANUAL OVERRIDE]" in logs[-1]:
        return "node_3_upgrader"
    return "node_1_helper"


def route_from_helper(state: FactoryState):
    challenger_xml = state.get("challenger_xml", "")
    if "<GEM_BLUEPRINT>" in challenger_xml:
        return "node_2_construct"
    return END


def route_from_adjudicator(state: FactoryState):
    logs = state.get("error_log", [])
    if not logs:
        return END

    last_log = logs[-1]
    iteration_count = state.get("iteration_count", 0)

    if "[PASS]" in last_log or "[ESCALATE]" in last_log:
        return END

    if "[FAIL]" in last_log:
        if iteration_count < 3:
            print(
                f"    -> Routing back to Upgrader (Attempt {iteration_count}/3)")
            return "node_3_upgrader"
        else:
            print("    -> Max iterations reached. Forcing ESCALATE.")
            return END
    return END

# ==========================================
# GRAPH COMPILATION
# ==========================================


builder = StateGraph(FactoryState)

# 1. Add Nodes
builder.add_node("node_1_helper", node_helper)
builder.add_node("node_2_construct", node_construct)
builder.add_node("node_3_upgrader", node_upgrader)
builder.add_node("node_4_adjudicator", node_adjudicator)

# 2. Add Edges (כולל התיקונים למעגל ה-QA והכניסה)
builder.add_conditional_edges(START, route_from_start)
builder.add_conditional_edges("node_1_helper", route_from_helper)
builder.add_edge("node_2_construct", "node_4_adjudicator")
builder.add_edge("node_3_upgrader", "node_4_adjudicator")  # סגירת מעגל ה-QA
builder.add_conditional_edges("node_4_adjudicator", route_from_adjudicator)

# 3. Compile Graph
graph = builder.compile()

