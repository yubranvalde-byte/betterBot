def _strip_thought_process(text: str) -> str:
    """Removes internal <thought_process> blocks before appending assistant turns to history."""
    return re.sub(
        r"<thought_process>.*?</thought_process>",
        "",
        text or "",
        flags=re.DOTALL | re.IGNORECASE,
    ).strip()


