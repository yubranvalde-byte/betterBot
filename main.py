def node_helper(state: FactoryState):
    """
    Node 1 (The Helper): Converts natural language into basic XML.
    """
    print(">>> Executing Node 1: The Helper")
    user_input = state.get("user_input", "")

    # ארכיטקטורת ייצור: הפרדה מוחלטת בין חוקי מערכת לקלט משתמש
    prompt = ChatPromptTemplate.from_messages([
        ("system", HELPER_PROMPT),
        ("human", "{user_input}")
    ])
    chain = prompt | llm

    response = chain.invoke({"user_input": user_input})
    raw_content = response.content

    # --- Data Normalization (חילוץ בטוח מרשימות) ---
    if isinstance(raw_content, list):
        content = "".join(part.get("text", "") if isinstance(
            part, dict) else str(part) for part in raw_content)
    else:
        content = str(raw_content)

    if not content.strip():
        print("\n" + "!"*50)
        print(">>> [CRITICAL] LLM RETURNED EMPTY PAYLOAD")
        print(">>> Inspecting Raw Metadata:")
        print(response.response_metadata)
        print("!"*50 + "\n")

    return {"challenger_xml": content}


def node_construct(state: FactoryState):
    """
    Node 2 (The Construct): Compiles XML into a complete System Prompt.
    """
    print(">>> Executing Node 2: The Construct")
    challenger_xml = state.get("challenger_xml", "")

    prompt = PromptTemplate.from_template(CONSTRUCT_PROMPT)
    chain = prompt | llm

    response = chain.invoke({"challenger_xml": challenger_xml})
    raw_content = response.content

    # --- Data Normalization (חילוץ בטוח מרשימות) ---
    if isinstance(raw_content, list):
        content = "".join(part.get("text", "") if isinstance(
            part, dict) else str(part) for part in raw_content)
    else:
        content = str(raw_content)

    return {"challenger_prompt": content}


class UpgraderOutput(BaseModel):
    """
    Schema for ensuring atomic updates, incorporating internal reasoning to maintain CoT.
    """
    skeleton: str = Field(
        description="Structural map of the exact sections requiring modification.")
    thought_process: str = Field(
        description="Granular impact analysis and variance minimization plan.")
    updated_xml: str = Field(
        description="The fully revised XML blueprint, incorporating all corrections.")
    updated_prompt: str = Field(
        description="The fully revised System Prompt, incorporating all corrections.")


def node_upgrader(state: FactoryState):
    """
    Node 3 (The Upgrader): Editor receiving change commands.
    Reads Champions and Error Log, overwrites Challengers.
    """
    print(">>> Executing Node 3: The Upgrader")

    champion_xml = state.get("champion_xml", "")
    champion_prompt = state.get("champion_prompt", "")
    error_log = state.get("error_log", [])

    formatted_errors = "\n".join(
        error_log) if error_log else "No specific errors provided."

    # שימוש במשתנה המיובא
    prompt = PromptTemplate.from_template(UPGRADER_PROMPT)
    structured_llm = llm.with_structured_output(UpgraderOutput)
    chain = prompt | structured_llm

    response = chain.invoke({
        "champion_xml": champion_xml,
        "champion_prompt": champion_prompt,
        "error_log": formatted_errors
    })

    return {
        "challenger_xml": response.updated_xml,
        "challenger_prompt": response.updated_prompt
    }


class AdjudicatorDecision(BaseModel):
    step_back: str = Field(
        description="Abstraction of the core intent and foundational success criteria.")
    audit_process: str = Field(
        description="Execution of the meticulous 6-Step Supervisory Protocol.")
    status: str = Field(description="Strictly one of: PASS, FAIL, ESCALATE")
    reason: str = Field(
        description="Detailed QA feedback analyzing the failure or success")
    correction_directive: str = Field(
        description="If FAIL, provide absolute, operative code directives for The Upgrader to execute. If PASS, return 'None'.")
    replace_champion: bool = Field(
        description="True if Challenger is better than Champion, regardless of PASS/FAIL status.")


def node_adjudicator(state: FactoryState):
    """
    Node 4 (The Adjudicator - QA): Gatekeeper utilizing Pydantic routing schemas.
    """
    print(">>> Executing Node 4: The Adjudicator")

    iteration_count = state.get("iteration_count", 0)
    user_input = state.get("user_input", "")
    champion_xml = state.get("champion_xml", "")
    champion_prompt = state.get("champion_prompt", "")
    challenger_xml = state.get("challenger_xml", "")
    challenger_prompt = state.get("challenger_prompt", "")
    error_log = state.get("error_log", [])

    structured_llm = llm.with_structured_output(AdjudicatorDecision)

    if iteration_count == 0:
        print("    -> Mode: Baseline QA (Iteration 0)")

        # שימוש בפרומפט ה-Baseline המיובא
        prompt = PromptTemplate.from_template(ADJUDICATOR_BASELINE_PROMPT)
        chain = prompt | structured_llm
        decision = chain.invoke({
            "user_input": user_input,
            "challenger_xml": challenger_xml,
            "challenger_prompt": challenger_prompt,
            "iteration_count": iteration_count
        })

    else:
        print(f"    -> Mode: Regression QA (Iteration {iteration_count})")
        formatted_errors = "\n".join(error_log) if error_log else "None"

        # שימוש בפרומפט ה-Regression המיובא
        prompt = PromptTemplate.from_template(ADJUDICATOR_REGRESSION_PROMPT)
        chain = prompt | structured_llm
        decision = chain.invoke({
            "user_input": user_input,
            "champion_xml": champion_xml,
            "champion_prompt": champion_prompt,
            "challenger_xml": challenger_xml,
            "challenger_prompt": challenger_prompt,
            "error_log": formatted_errors,
            "iteration_count": iteration_count
        })

    print(f"    -> Decision: {decision.status}")

    # --- לוגיקת עדכון ה-State (כולל תיקון ה-Baseline Trap לאיטרציה 0) ---
    state_update = {"iteration_count": iteration_count + 1}

    if decision.status == "PASS" or decision.replace_champion or iteration_count == 0:
        state_update["champion_xml"] = challenger_xml
        state_update["champion_prompt"] = challenger_prompt

    if decision.status == "PASS":
        # תוספת קריטית לזיהוי הצלחה בניתוב
        state_update["error_log"] = ["[PASS] System approved."]

    if decision.status in ["FAIL", "ESCALATE"]:
        formatted_message = f"[{decision.status}] Reason: {decision.reason} | Directive: {decision.correction_directive}"
        state_update["error_log"] = [formatted_message]

    return state_update

