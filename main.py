def _normalize_content(raw_content: Any) -> str:
    """Safely extracts string text from LangChain message content."""
    if isinstance(raw_content, list):
        return "".join(
            part.get("text", "") if isinstance(part, dict) else str(part)
            for part in raw_content
        )
    return str(raw_content)


def _invoke_with_compiler_fallback(
    prompt_template: Any,
    inputs: Dict[str, Any],
    structured_schema: Any = None,
    target_type: str = "SYSTEM_PROMPT",
) -> Any:
    """
    Routes Construct/Upgrader execution using calibrated thinking budgets:
    - HYBRID_BUNDLE uses COMPILER_MODEL (`thinking_level="medium"`) with fallback to FAST_MODEL.
    - SYSTEM_PROMPT / SKILL_PACKAGE default directly to FAST_MODEL (`thinking_level="medium"`).
    """
    normalized_target = (target_type or "SYSTEM_PROMPT").strip().upper()
    if normalized_target == "HYBRID_BUNDLE" and COMPILER_MODEL != FAST_MODEL:
        models = [compiler_llm, construct_llm, llm]
    else:
        models = [construct_llm, llm]

    last_exc = None
    for idx, model_instance in enumerate(models):
        t0 = time.perf_counter()
        try:
            target = (
                model_instance.with_structured_output(structured_schema)
                if structured_schema is not None
                else model_instance
            )
            chain = prompt_template | target
            result = chain.invoke(inputs)
            latency_ms = (time.perf_counter() - t0) * 1000.0
            print(
                f"    -> [CompilerLLM] model={model_instance.model} "
                f"thinking_level={model_instance.thinking_level} "
                f"target_type={normalized_target} latency_ms={latency_ms:.1f}"
            )
            return result
        except Exception as exc:
            last_exc = exc
            if idx < len(models) - 1:
                next_model = models[idx + 1]
                print(
                    f"    -> [WARN] Compiler model '{model_instance.model}' "
                    f"(thinking_level={model_instance.thinking_level}) failed ({exc}); "
                    f"falling back to '{next_model.model}' "
                    f"(thinking_level={next_model.thinking_level})."
                )
    raise last_exc


def evaluate_with_decision_model(
    context_text: str,
    questions: List[Dict[str, Any]],
) -> Dict[str, Any]:
    """
    Calls `gemini-decision-1` via the Gemini Decisions REST API
    (`v1beta/decisions`) for zero-output-token readiness routing and rubric scoring.
    Includes a 5.0s timeout and non-blocking fallback so pipeline execution never stalls.
    """
    if not GOOGLE_API_KEY or GOOGLE_API_KEY == "MISSING_GOOGLE_API_KEY":
        return {
            "used_decision_model": False,
            "answers": {},
            "latency_ms": 0.0,
            "error": "Missing GOOGLE_API_KEY",
        }

    choice_descriptions = {
        "SKILL_PACKAGE": "Modular agent skill package (SKILL.md + optional references/*) with triggers and SOP",
        "SYSTEM_PROMPT": "Standalone autonomous persona or assistant constitutional system prompt",
        "HYBRID_BUNDLE": "Combined bundle requiring both a core System Prompt and a modular Skill package",
    }

    questions_map: Dict[str, Dict[str, Any]] = {}
    for q in questions:
        q_name = q["name"]
        q_type = q.get("type", "noul")
        q_text = q.get("question", "")

        if q_type == "choice":
            choices = q.get("choices", [])
            criteria = (
                choices
                if isinstance(choices, dict)
                else {str(c): choice_descriptions.get(str(c), str(c)) for c in choices}
            )
            questions_map[q_name] = {
                "type": "choice",
                "instructions": q_text,
                "criteria": criteria,
            }
        elif q_type == "score":
            rubric_desc = q.get("rubric", {})
            if isinstance(rubric_desc, dict):
                sorted_keys = sorted(rubric_desc.keys(), key=lambda k: int(k))
                criteria_list = [str(rubric_desc[k]) for k in sorted_keys]
            else:
                criteria_list = [str(x) for x in rubric_desc]
            questions_map[q_name] = {
                "type": "score",
                "instructions": q_text,
                "criteria": criteria_list,
            }
        else:  # "noul" Yes/No probability
            questions_map[q_name] = {
                "type": "noul",
                "instructions": q_text,
            }

    url = (
        f"https://generativelanguage.googleapis.com/v1beta/decisions"
        f"?key={GOOGLE_API_KEY}"
    )
    payload = {
        "model": DECISION_MODEL,
        "input": context_text.strip() or "No context provided.",
        "questions": questions_map,
    }

    t0 = time.perf_counter()
    try:
        resp = requests.post(url, json=payload, timeout=5.0)
        resp.raise_for_status()
        latency_ms = (time.perf_counter() - t0) * 1000.0
        data = resp.json()
        raw_answers = data.get("answers", {})

        normalized_answers: Dict[str, Any] = {}
        for q in questions:
            q_name = q["name"]
            q_type = q.get("type", "noul")
            ans_obj = raw_answers.get(q_name)

            if q_type == "choice":
                choices = q.get("choices", [])
                valid_choices = (
                    list(choices.keys()) if isinstance(choices, dict) else list(choices)
                )
                raw_val = (
                    ans_obj.get("choice") if isinstance(ans_obj, dict) else ans_obj
                )
                normalized_answers[q_name] = (
                    str(raw_val)
                    if str(raw_val) in valid_choices
                    else (valid_choices[0] if valid_choices else "")
                )
            elif q_type == "score":
                min_s = float(q.get("min_score", 0))
                max_s = float(q.get("max_score", 5))
                raw_val = (
                    ans_obj.get("score") if isinstance(ans_obj, dict) else ans_obj
                )
                try:
                    num = float(raw_val)
                except (TypeError, ValueError):
                    num = min_s
                normalized_answers[q_name] = max(min_s, min(max_s, num))
            else:
                raw_val = (
                    ans_obj.get("noul") if isinstance(ans_obj, dict) else ans_obj
                )
                if isinstance(raw_val, str):
                    lowered = raw_val.strip().lower()
                    num = 1.0 if lowered in ("yes", "true", "1") else 0.0
                else:
                    try:
                        num = float(raw_val)
                    except (TypeError, ValueError):
                        num = 0.0
                normalized_answers[q_name] = max(0.0, min(1.0, num))

        print(
            f"    -> [DecisionEngine] latency_ms={latency_ms:.1f} "
            f"status=ok model={DECISION_MODEL}"
        )
        result: Dict[str, Any] = {
            "used_decision_model": True,
            "answers": normalized_answers,
            "latency_ms": round(latency_ms, 1),
        }
        result.update(normalized_answers)
        return result
    except Exception as exc:
        latency_ms = (time.perf_counter() - t0) * 1000.0
        print(
            f"    -> [DecisionEngine] latency_ms={latency_ms:.1f} "
            f"status=fallback error={exc}"
        )
        return {
            "used_decision_model": False,
            "answers": {},
            "latency_ms": round(latency_ms, 1),
            "error": str(exc),
        }


