def node_upgrader(state: FactoryState):
    """
    Node 3 (The Upgrader 2.0): Atomic delta-patching editor receiving QA directives or manual overrides.
    Reads Champions and Error Log, merges modified/new `### FILE:` blocks into `reference_files`,
    removes `### DELETE:` paths, and preserves untouched auxiliary files.
    """
    print(">>> Executing Node 3: The Upgrader")

    champion_xml = state.get("champion_xml") or state.get("challenger_xml", "")
    base_prompt = state.get("champion_prompt") or state.get("challenger_prompt", "")
    champion_prompt = format_artifact_with_references(
        base_prompt, state.get("reference_files")
    )
    error_log = state.get("error_log", [])
    is_override = bool(state.get("is_manual_override")) or bool(
        error_log and "[MANUAL OVERRIDE]" in error_log[-1]
    )

    formatted_errors = (
        "\n".join(error_log) if error_log else "No specific errors provided."
    )

    current_target = state.get("target_type") or extract_blueprint_meta(
        champion_xml
    ).get("target_type", "SYSTEM_PROMPT")
    needs_scripts = (
        False
        if current_target == "SYSTEM_PROMPT"
        else (
            bool(state.get("needs_scripts"))
            or is_needs_scripts(
                state.get("readiness_scores"),
                target_type=current_target,
                fallback_xml=champion_xml,
            )
        )
    )
    is_repo_context = bool(state.get("is_repo_context")) or is_repo_context_mode(
        state.get("readiness_scores"),
        fallback_xml=champion_xml,
        ref_files=state.get("reference_files"),
    )
    effort_tier = normalize_effort_tier(state.get("effort_tier"))
    att_ctx = format_context_attachments(state, max_chars=12000)
    upgrader_xml_input = f"{champion_xml}\n\n{att_ctx}" if att_ctx else champion_xml
    prompt = PromptTemplate.from_template(UPGRADER_PROMPT)
    response, telemetry = _invoke_role_with_fallback(
        role="node_3_upgrader",
        prompt_template=prompt,
        inputs={
            "champion_xml": upgrader_xml_input,
            "champion_prompt": champion_prompt,
            "error_log": formatted_errors,
            "needs_scripts": "True" if needs_scripts else "False",
            "is_repo_context": "True" if is_repo_context else "False",
        },
        structured_schema=UpgraderOutput,
        model_overrides=state.get("model_overrides"),
        target_type=current_target,
        effort_tier=effort_tier,
    )

    meta = extract_blueprint_meta(response.updated_xml)
    raw_updated_prompt = response.updated_prompt or ""
    primary_prompt, ref_files = parse_compiled_artifacts(raw_updated_prompt)
    deleted_paths = parse_deleted_artifacts(raw_updated_prompt)

    merged_refs: Dict[str, str] = {}
    for existing_path, existing_content in (state.get("reference_files") or {}).items():
        norm_existing = normalize_artifact_path(existing_path)
        if norm_existing:
            merged_refs[norm_existing] = existing_content
    merged_refs.update(ref_files)
    for del_path in deleted_paths:
        merged_refs.pop(del_path, None)

    stripped_primary = re.sub(
        r"<compilation_check>.*?</compilation_check>",
        "",
        primary_prompt or "",
        flags=re.DOTALL | re.IGNORECASE,
    ).strip()
    if not stripped_primary:
        primary_prompt = base_prompt
    elif (
        meta["target_type"] == "HYBRID_BUNDLE"
        and (
            "SYSTEM_PROMPT.md" in merged_refs
            or "AGENTS.md" in merged_refs
            or "SKILL.md" in merged_refs
        )
        and primary_prompt.lstrip().startswith("### FILE:")
    ):
        rebuilt_sections = [
            f"### FILE: {fp}\n{merged_refs[fp]}"
            for fp in ("SYSTEM_PROMPT.md", "AGENTS.md", "SKILL.md")
            if fp in merged_refs
        ]
        if rebuilt_sections:
            comp_match = re.search(
                r"(<compilation_check>.*?</compilation_check>)",
                primary_prompt,
                flags=re.DOTALL | re.IGNORECASE,
            )
            rebuilt_body = "\n\n".join(rebuilt_sections)
            primary_prompt = (
                f"{comp_match.group(1).strip()}\n\n{rebuilt_body}".strip()
                if comp_match
                else rebuilt_body
            )

    has_compiled_scripts = any(
        k.endswith(".py") and (k.startswith("scripts/") or "/scripts/" in k)
        for k in merged_refs
    )
    updated_needs_scripts = (
        False
        if meta["target_type"] == "SYSTEM_PROMPT"
        else (
            needs_scripts
            or has_blueprint_scripts(response.updated_xml)
            or has_compiled_scripts
        )
    )

    update: Dict[str, Any] = {
        "challenger_xml": response.updated_xml,
        "challenger_prompt": primary_prompt,
        "previous_artifact_snapshot": champion_prompt,
        "target_type": meta["target_type"],
        "needs_scripts": updated_needs_scripts,
        "is_repo_context": is_repo_context
        or is_repo_context_mode(None, response.updated_xml, merged_refs),
        "reference_files": merged_refs,
        "is_manual_override": is_override,
        "model_telemetry": {
            "node_3_upgrader": telemetry,
            "last_execution": telemetry,
        },
    }
    if meta["slug_name"]:
        update["slug_name"] = meta["slug_name"]
    return update


