def run_factory():
    print("\n" + "="*50)
    print("🧠 Welcome to The Intelligence Factory 🧠")
    print("="*50)

    # טריגר ראשוני להפעלת המערכת
    initial_input = input(
        "\n[System] Describe the AI Agent you want to build:\nYou: ")

    # אתחול ה-State הראשי בזכרון
    state: FactoryState = {
        "user_input": initial_input,
        "champion_xml": "",
        "champion_prompt": "",
        "challenger_xml": "",
        "challenger_prompt": "",
        "error_log": [],
        "iteration_count": 0
    }

    while True:
        print("\n[System] Invoking the Graph...")
        # הרצת הגרף עם ה-State הנוכחי
        state = graph.invoke(state)

        # חילוץ משתנים לאחר עצירת הגרף (END)
        iteration_count = state.get("iteration_count", 0)
        challenger_xml = state.get("challenger_xml", "")
        error_log = state.get("error_log", [])
        last_log = error_log[-1] if error_log else ""

        # תרחיש א': לולאת הראיון (העוזר שואל שאלות מקדימות)
        if "<GEM_BLUEPRINT>" not in challenger_xml and iteration_count == 0:
            # הזרקת תמיכה כפויה בעברית לטרמינל של חלונות
            import sys
            sys.stdout.reconfigure(encoding='utf-8')

            print("\n[The Helper] says:")

            # בדיקת דיבוג: האם המודל החזיר טקסט ריק?
            if not challenger_xml.strip():
                print(
                    ">> [DEBUG ERROR] The AI returned an empty string! No text was generated.")
            else:
                print(challenger_xml)

            user_reply = input("\nYou: ")

            # שרשור השיחה לזיכרון והרצה מחדש
            state["user_input"] += f"\nAssistant: {challenger_xml}\nUser: {user_reply}"
            continue

        # תרחיש ג': הצלחה מוחלטת
        if "[PASS]" in last_log:
            print("\n" + "🌟"*20)
            print("SUCCESS! The system has approved the final prompt.")
            print("🌟"*20 + "\n")
            print("--- FINAL SYSTEM PROMPT ---")
            print(state.get("champion_prompt"))
            break

        # תרחיש ב': הפעלת מפסק פחת / התערבות ידנית (Escalation)
        if "[ESCALATE]" in last_log:
            print("\n" + "⚠️"*20)
            print(
                "SYSTEM ESCALATED: Max iterations reached. Manual intervention required.")
            print("⚠️"*20)

            print("\n--- CURRENT CHAMPION XML ---")
            print(state.get("champion_xml"))

            print("\n--- CURRENT CHAMPION PROMPT ---")
            print(state.get("champion_prompt"))

            print("\n[System] Enter manual correction directives for the Upgrader.")
            user_correction = input("Directive (or type 'exit' to quit): ")

            if user_correction.strip().lower() == 'exit':
                print("Exiting Factory...")
                break

            # הטמעת הפקודה הידנית בלוג, איפוס איטרציות, ושליחה ל-Upgrader
            state["error_log"].append(f"[MANUAL OVERRIDE] {user_correction}")
            state["iteration_count"] = 1
            continue


if __name__ == "__main__":
    run_factory()
