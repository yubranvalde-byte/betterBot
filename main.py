def has_blueprint_xml(xml_text: str) -> bool:
    """Detects BetterBot 2.0 <ARTIFACT_BLUEPRINT> or legacy <GEM_BLUEPRINT>."""
    if not xml_text:
        return False
    return bool(
        re.search(
            r"<(ARTIFACT_BLUEPRINT|GEM_BLUEPRINT)\b",
            xml_text,
            flags=re.IGNORECASE,
        )
    )


def extract_blueprint_meta(xml_text: str) -> Dict[str, str]:
    """Extracts TARGET_TYPE and SLUG_NAME from blueprint XML with safe defaults."""
    target_match = re.search(
        r"<TARGET_TYPE>\s*(.*?)\s*</TARGET_TYPE>",
        xml_text or "",
        flags=re.DOTALL | re.IGNORECASE,
    )
    slug_match = re.search(
        r"<SLUG_NAME>\s*(.*?)\s*</SLUG_NAME>",
        xml_text or "",
        flags=re.DOTALL | re.IGNORECASE,
    )
    raw_target = target_match.group(1).strip().upper() if target_match else "SYSTEM_PROMPT"
    if raw_target not in VALID_TARGET_TYPES:
        raw_target = "SYSTEM_PROMPT"
    slug_name = slug_match.group(1).strip() if slug_match else ""
    return {"target_type": raw_target, "slug_name": slug_name}


def _extract_compilation_body(raw_text: str) -> Tuple[str, str]:
    """Extracts any `<compilation_check>` block and unwraps an outer markdown fence."""
    if not raw_text:
        return "", ""
    comp_match = re.search(
        r"(<compilation_check>.*?</compilation_check>)",
        raw_text,
        flags=re.DOTALL | re.IGNORECASE,
    )
    comp_block = comp_match.group(1).strip() if comp_match else ""
    body = re.sub(
        r"<compilation_check>.*?</compilation_check>",
        "",
        raw_text,
        flags=re.DOTALL | re.IGNORECASE,
    ).strip()

    code_match = re.search(
        r"^`{3,4}(?:markdown|md)?\s*\n(.*?)\n`{3,4}\s*$",
        body,
        flags=re.DOTALL,
    )
    inner_body = code_match.group(1).strip() if code_match else body
    return comp_block, inner_body


def parse_deleted_artifacts(raw_text: str) -> List[str]:
    """Extracts and sanitizes `### DELETE: <path>` directives from Upgrader outputs."""
    if not raw_text:
        return []
    _, inner_body = _extract_compilation_body(raw_text)
    deleted: List[str] = []
    seen = set()
    for match in re.finditer(r"(?m)^###\s+DELETE:\s*(.+?)\s*$", inner_body):
        norm = normalize_artifact_path(match.group(1))
        if norm and norm not in seen:
            seen.add(norm)
            deleted.append(norm)
    return deleted


def _strip_python_code_fence(text: str) -> str:
    """Defensively strips outer Markdown code fences (e.g. ```python ... ```) from .py artifact blocks."""
    if not text:
        return ""
    cleaned = text.strip()
    cleaned = re.sub(
        r"^`{3,4}(?:python3?|py)?[ \t]*\r?\n",
        "",
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(r"\r?\n`{3,4}[ \t]*$", "", cleaned)
    return cleaned.strip()


def parse_compiled_artifacts(raw_text: str) -> Tuple[str, Dict[str, str]]:
    """
    Splits `### FILE: <path>` sections from Construct/Upgrader outputs, supporting
    flat (`references/...`, `scripts/...`) and nested (`skills/<slug>/...`) relative paths.
    Auxiliary files are extracted into `reference_files` while the primary artifact
    (preserving any `<compilation_check>`) remains in `challenger_prompt`.
    """
    if not raw_text:
        return "", {}

    comp_block, inner_body = _extract_compilation_body(raw_text)
    has_delete_directives = bool(parse_deleted_artifacts(raw_text))
    if has_delete_directives:
        inner_body = re.sub(
            r"(?m)^###\s+DELETE:\s*.+?\s*$\n?", "", inner_body
        ).strip()

    parts = re.split(r"(?m)^###\s+FILE:\s*(.+?)\s*$", inner_body)
    if len(parts) <= 1:
        if has_delete_directives:
            if not inner_body:
                return comp_block, {}
            primary_only = (
                f"{comp_block}\n\n{inner_body}".strip() if comp_block else inner_body
            )
            return primary_only, {}
        return raw_text, {}

    preamble = parts[0].strip()
    all_files: Dict[str, str] = {}
    reference_files: Dict[str, str] = {}

    for i in range(1, len(parts), 2):
        file_path = normalize_artifact_path(parts[i])
        file_content = parts[i + 1].strip() if i + 1 < len(parts) else ""
        if not file_path:
            continue
        if file_path.endswith(".py"):
            file_content = _strip_python_code_fence(file_content)
        all_files[file_path] = file_content
        reference_files[file_path] = file_content

    if preamble:
        primary_body = preamble
    else:
        primary_sections = [
            f"### FILE: {fp}\n{fc}"
            for fp, fc in all_files.items()
            if fp in ("SYSTEM_PROMPT.md", "AGENTS.md", "SKILL.md")
        ]
        primary_body = "\n\n".join(primary_sections)

    if primary_body:
        primary_output = (
            f"{comp_block}\n\n{primary_body}".strip() if comp_block else primary_body
        )
    else:
        primary_output = comp_block
    return primary_output, reference_files


ATTACHMENT_VERBATIM_MAX_BYTES = 4096
ATTACHMENT_TEXT_MAX_CHARS = 120_000
ATTACHMENT_BINARY_MIMES = frozenset(
    {"application/pdf", "image/png", "image/jpeg", "image/webp"}
)


def distill_attachment(
    filename: str, mime_type: str, raw_bytes: bytes
) -> Dict[str, Any]:
    """
    Ingest-Once Distillation:
    - Small UTF-8 text/code (<= 4096 bytes): stored verbatim with 0 LLM tokens.
    - Large UTF-8 text/code (> 4096 bytes) and images/PDFs: distilled once via FAST_MODEL (`low`).
    Never stores raw_bytes or Base64 in the returned dictionary.
    """
    clean_name = str(filename or "attachment").strip() or "attachment"
    clean_mime = str(mime_type or "text/plain").strip().lower()
    size_bytes = len(raw_bytes or b"")
    created_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
    att_id = uuid.uuid4().hex[:10]

    if clean_mime not in ATTACHMENT_BINARY_MIMES and size_bytes <= ATTACHMENT_VERBATIM_MAX_BYTES:
        decoded = (raw_bytes or b"").decode("utf-8", errors="replace").strip()
        return {
            "id": att_id,
            "filename": clean_name,
            "mime_type": clean_mime,
            "size_bytes": size_bytes,
            "mode": "verbatim",
            "digest": decoded,
            "created_at": created_at,
        }

    system_prompt = ATTACHMENT_DIGEST_PROMPT.format(
        filename=clean_name, mime_type=clean_mime
    )

    if clean_mime in ATTACHMENT_BINARY_MIMES:
        b64_payload = base64.b64encode(raw_bytes or b"").decode("ascii")
        human_msg = HumanMessage(
            content=[
                {
                    "type": "text",
                    "text": (
                        f"Distill the attached {clean_mime} file `{clean_name}` "
                        f"({size_bytes} bytes) into a dense Context Digest."
                    ),
                },
                {
                    "type": "media",
                    "mime_type": clean_mime,
                    "data": b64_payload,
                },
            ]
        )
        del b64_payload
    else:
        raw_text = (raw_bytes or b"").decode("utf-8", errors="replace")
        truncated_note = ""
        if len(raw_text) > ATTACHMENT_TEXT_MAX_CHARS:
            raw_text = raw_text[:ATTACHMENT_TEXT_MAX_CHARS]
            truncated_note = f"\n[Truncated at {ATTACHMENT_TEXT_MAX_CHARS} chars]"
        human_msg = HumanMessage(
            content=(
                f"Distill the attached file `{clean_name}` ({clean_mime}, {size_bytes} bytes) "
                f"into a dense Context Digest:\n\n{raw_text}{truncated_note}"
            )
        )

    messages = [SystemMessage(content=system_prompt), human_msg]
    try:
        response, _ = _invoke_role_with_fallback(
            role="betty",
            messages=messages,
            thinking_level="low",
            effort_tier="low",
        )
        digest_text = _normalize_content(response.content).strip()
    except Exception as exc:
        safe_err = _sanitize_error_text(exc)
        if clean_mime not in ATTACHMENT_BINARY_MIMES:
            fallback_text = (raw_bytes or b"").decode("utf-8", errors="replace")[:4000]
            digest_text = f"[Fallback excerpt due to distiller error: {safe_err}]\n{fallback_text}"
        else:
            raise RuntimeError(f"Multimodal attachment distillation failed: {safe_err}") from exc

    return {
        "id": att_id,
        "filename": clean_name,
        "mime_type": clean_mime,
        "size_bytes": size_bytes,
        "mode": "distilled",
        "digest": digest_text,
        "created_at": created_at,
    }


def format_context_attachments(
    state: Optional[Dict[str, Any]], max_chars: int = 12000
) -> str:
    """Formats session `context_attachments` digests into a bounded `<ATTACHED_CONTEXT>` block."""
    attachments = (state or {}).get("context_attachments") or []
    if not isinstance(attachments, list) or not attachments:
        return ""
    blocks: List[str] = []
    for item in attachments:
        if not isinstance(item, dict):
            continue
        digest = str(item.get("digest") or "").strip()
        if not digest:
            continue
        fname = str(item.get("filename") or "attachment")
        mime = str(item.get("mime_type") or "text/plain")
        mode = str(item.get("mode") or "verbatim")
        blocks.append(f"### ATTACHMENT: {fname} ({mime}, {mode})\n{digest}")
    if not blocks:
        return ""
    joined = "\n\n".join(blocks)
    if max_chars > 0 and len(joined) > max_chars:
        joined = joined[: max_chars - 24].rstrip() + "\n...[context truncated]"
    return f"<ATTACHED_CONTEXT>\n{joined}\n</ATTACHED_CONTEXT>"


def format_artifact_with_references(
    primary_prompt: str,
    reference_files: Optional[Dict[str, str]] = None,
) -> str:
    """
    Reconstructs the unified multi-file artifact view (primary prompt + auxiliary `### FILE:` blocks)
    so Node 3 (Upgrader) and Node 4 (Adjudicator) audit and edit the full Skill/Bundle/Suite package.
    """
    if not reference_files:
        return primary_prompt or ""
    base = (primary_prompt or "").strip()
    body_without_checks = re.sub(
        r"<compilation_check>.*?</compilation_check>",
        "",
        base,
        flags=re.DOTALL | re.IGNORECASE,
    )
    extra_sections = []
    for rel_path, content in reference_files.items():
        norm_path = normalize_artifact_path(rel_path)
        if not norm_path:
            continue
        header_re = rf"(?m)^###\s+FILE:\s*{re.escape(norm_path)}\s*$"
        if re.search(header_re, body_without_checks):
            continue
        extra_sections.append(f"### FILE: {norm_path}\n{content}")
    if not extra_sections:
        return base
    return f"{base}\n\n" + "\n\n".join(extra_sections) if base else "\n\n".join(extra_sections)

