# Enforces Overwrite logic to prevent Context Window Bloat


def replace_value(old_val, new_val):
    return new_val


class FactoryState(TypedDict):
    user_input: str

    # Champion: The current best approved version
    champion_xml: Annotated[str, replace_value]
    champion_prompt: Annotated[str, replace_value]

    # Challenger: The new version generated by Node 3, waiting for Node 4 QA
    challenger_xml: Annotated[str, replace_value]
    challenger_prompt: Annotated[str, replace_value]

    # Error Log: The ONLY field that appends data.
    error_log: Annotated[List[str], operator.add]

    # Circuit breaker and Iteration 0 flag
    iteration_count: Annotated[int, replace_value]


